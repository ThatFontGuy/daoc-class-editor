//! Generates a trainer NPC's `.cs` file - the `GameTrainer` subclass that lets a player get
//! promoted into a custom class - and spawns it in the world by deep-cloning an existing trainer
//! NPC's full stat/position profile.
//!
//! This mirrors a real precedent in the server source (`SluaghbinderTrainer.cs`): nothing beyond
//! the game client's built-in class list is directly selectable at character creation, so a
//! brand-new custom class needs the same classic-DAoC workaround every post-launch class uses -
//! create a character as the realm-appropriate archetype (e.g. "Midgard Rogue"), then a trainer
//! promotes them into the specific class at some level. `GameTrainer.TrainedClass` is typed as
//! the `eCharacterClass` enum, but C# lets you cast an arbitrary int to an enum with no matching
//! named member at all - `(eCharacterClass)64` is valid even though nothing in the enum is named
//! that - so this works without needing an enum entry for the custom class, same as the class
//! file itself.
//!
//! Also found a real wrinkle during this design: `GameTrainer.CanPromotePlayer`'s *default*
//! implementation resolves the archetype to promote from by walking exactly one level up the C#
//! inheritance chain and matching base-class-name strings - which breaks for a class cloned from
//! an *already-promoted* class (e.g. a Nosferatu cloned from Shadowblade, two levels above the
//! Midgard Rogue archetype). So the generated trainer always overrides `CanPromotePlayer`/
//! `CanTrain` itself with an explicit, raw-ID archetype check instead of relying on that default -
//! exactly what `SluaghbinderTrainer.cs` had to do for the same reason.

use crate::deploy::{SshConfig, run_remote_sql, run_remote_sql_json};
use serde::{Deserialize, Serialize};
use serde_json::Value;

#[derive(Debug, Clone, Serialize, Deserialize)]
pub struct TrainerRequest {
    pub class_id: i32,
    pub class_name: String,
    /// The C# type name for the trainer itself, e.g. "NosferatuTrainer".
    pub trainer_class_ident: String,
    /// Must match the NPC's own `Guild` DB field exactly - that's how `[NPCGuildScript]` binds a
    /// script to an NPC.
    pub guild_name: String,
    pub realm: String,
    /// The archetype a player must currently be (and have reached `min_level` as) to be offered
    /// promotion - see `classdata::root_archetype`.
    pub archetype_id: i32,
    pub archetype_name: String,
    pub min_level: i32,
}

pub fn generate_trainer_code(req: &TrainerRequest) -> String {
    format!(
        r#"/*
 * {class_name} Trainer: promotes a level {min_level}+ {archetype_name} into {class_name}.
 * Generated by DAoC Class Editor (https://github.com/ThatFontGuy/daoc-class-editor).
 *
 * Classic DAoC pattern: {class_name} isn't in the game client's built-in class list, so it can't
 * be picked at character creation - a player creates a {archetype_name} instead and this trainer
 * offers to promote them once they reach level {min_level}, same as every other post-launch
 * class (see DOL.GS.Trainer.SluaghbinderTrainer for the real precedent this follows).
 *
 * Deploy to your server's <server-folder>/bin/scripts/ folder (not a top-level scripts/ - the
 * server's own RootDirectory always resolves to wherever its own executable lives) and restart,
 * then spawn an NPC with Guild = "{guild_name}" and ClassType =
 * "DOL.GS.Trainer.{trainer_class_ident}" for the server's runtime script compiler and
 * NPCGuildScript binding to pick this up.
 */
using DOL.GS.PacketHandler;

namespace DOL.GS.Trainer
{{
	[NPCGuildScript("{guild_name}", eRealm.{realm})]
	public class {trainer_class_ident} : GameTrainer
	{{
		public override eCharacterClass TrainedClass => (eCharacterClass){class_id};

		// No named eCharacterClass member exists for a tool-generated class (just like the class
		// file itself), but C# allows casting any int to an enum regardless - this is valid and
		// every (int)TrainedClass comparison elsewhere in GameTrainer still works correctly.

		public override bool CanTrain(GamePlayer player)
		{{
			if (player?.CharacterClass != null &&
				player.Realm == eRealm.{realm} &&
				player.CharacterClass.ID == {archetype_id} &&
				player.Level < {min_level})
			{{
				return true;
			}}

			return base.CanTrain(player);
		}}

		// Overridden rather than relying on the default CanPromotePlayer: that default resolves
		// the archetype to promote from by walking exactly one level up the C# inheritance chain,
		// which only works for a class promoted directly from its archetype - not one cloned from
		// an already-promoted class like {class_name}. This explicit check is correct regardless
		// of how many clone generations deep {class_name} is.
		public override bool CanPromotePlayer(GamePlayer player)
		{{
			if (player == null || player.Realm != eRealm.{realm} ||
				player.Level < {min_level} ||
				player.CharacterClass?.ID != {archetype_id})
				return false;

			var targetClass = ScriptMgr.FindCharacterClass((int)TrainedClass);
			return targetClass != null &&
				targetClass.EligibleRaces.Exists(r => r.ID == (eRace)player.Race) &&
				(!GlobalConstants.CLASS_GENDER_CONSTRAINTS_DICT.TryGetValue(TrainedClass, out eGender gender) ||
					gender == player.Gender);
		}}

		public override bool Interact(GamePlayer player)
		{{
			if (!base.Interact(player))
				return false;

			if (player.CharacterClass.ID == (int)TrainedClass)
			{{
				OfferTraining(player);
			}}
			else if (CanPromotePlayer(player))
			{{
				player.Out.SendMessage(Name + " says, \"Do you seek the [Path of the {class_name}]?\"", eChatType.CT_System, eChatLoc.CL_PopupWindow);
				if (!player.IsLevelRespecUsed)
					OfferRespecialize(player);
			}}
			else
			{{
				CheckChampionTraining(player);
			}}

			return true;
		}}

		public override bool WhisperReceive(GameLiving source, string text)
		{{
			if (!base.WhisperReceive(source, text))
				return false;

			GamePlayer player = source as GamePlayer;
			if (player == null)
				return false;

			if (string.Equals(text, "Path of the {class_name}", System.StringComparison.OrdinalIgnoreCase))
			{{
				if (CanPromotePlayer(player))
					PromotePlayer(player, (int)TrainedClass, "Welcome, {class_name}.", null);
			}}

			return true;
		}}
	}}
}}
"#,
        class_name = req.class_name,
        class_id = req.class_id,
        trainer_class_ident = req.trainer_class_ident,
        guild_name = req.guild_name,
        realm = req.realm,
        archetype_id = req.archetype_id,
        archetype_name = req.archetype_name,
        min_level = req.min_level,
    )
}

#[derive(Debug, Clone, Serialize, Deserialize)]
pub struct TrainerNpcCandidate {
    pub mob_id: String,
    pub name: String,
    pub guild: String,
    pub class_type: String,
    pub x: i64,
    pub y: i64,
    pub z: i64,
    pub heading: i64,
    pub region: i64,
    pub realm: i64,
    pub model: i64,
    pub level: i64,
}

fn str_field(row: &Value, key: &str) -> String {
    row.get(key)
        .and_then(Value::as_str)
        .unwrap_or("")
        .to_string()
}

fn int_field(row: &Value, key: &str) -> i64 {
    row.get(key).and_then(Value::as_i64).unwrap_or(0)
}

fn sql_quote(s: &str) -> String {
    s.replace('\'', "''")
}

/// Finds existing trainer NPCs to use as a location/stats template - searches `Guild` (the field
/// `[NPCGuildScript]` matches on) for `search`, e.g. "Rogue Trainer" or "Shadowblade Trainer", so
/// the new trainer can be placed right next to a real one rather than guessing coordinates.
pub fn find_trainer_npcs(
    cfg: &SshConfig,
    search: &str,
) -> Result<Vec<TrainerNpcCandidate>, String> {
    let sql = format!(
        "SELECT Mob_ID,Name,Guild,ClassType,X,Y,Z,Heading,Region,Realm,Model,Level FROM Mob WHERE Guild LIKE '%{}%' ORDER BY Name;",
        sql_quote(search)
    );
    let rows = run_remote_sql_json(cfg, &sql)?;
    Ok(rows
        .iter()
        .map(|r| TrainerNpcCandidate {
            mob_id: str_field(r, "Mob_ID"),
            name: str_field(r, "Name"),
            guild: str_field(r, "Guild"),
            class_type: str_field(r, "ClassType"),
            x: int_field(r, "X"),
            y: int_field(r, "Y"),
            z: int_field(r, "Z"),
            heading: int_field(r, "Heading"),
            region: int_field(r, "Region"),
            realm: int_field(r, "Realm"),
            model: int_field(r, "Model"),
            level: int_field(r, "Level"),
        })
        .collect())
}

/// Spawns a new trainer NPC by cloning every field of an existing one (`reference_mob_id`) - full
/// stats, speed, flags, brain, everything - except identity (a fresh `Mob_ID`), name, guild,
/// script class, and position (offset from the reference so it doesn't spawn on top of it).
pub fn spawn_trainer_npc(
    cfg: &SshConfig,
    reference_mob_id: &str,
    npc_name: &str,
    guild_name: &str,
    class_type: &str,
    offset_x: i64,
    offset_y: i64,
) -> Result<String, String> {
    let new_id = uuid::Uuid::new_v4().to_string();
    let sql = format!(
        "INSERT INTO Mob (Mob_ID, ClassType, TranslationId, Name, Suffix, Guild, ExamineArticle, \
         MessageArticle, X, Y, Z, Speed, Heading, Region, Model, Size, Strength, Constitution, \
         Dexterity, Quickness, Intelligence, Piety, Empathy, Charisma, Level, Realm, \
         EquipmentTemplateID, ItemsListTemplateID, NPCTemplateID, Race, Flags, AggroLevel, \
         AggroRange, MeleeDamageType, RespawnInterval, FactionID, BodyType, HouseNumber, Brain, \
         PathID, OwnerID, RoamingRange, IsCloakHoodUp, Gender, PackageID, VisibleWeaponSlots) \
         SELECT '{new_id}', '{class_type_q}', TranslationId, '{name_q}', Suffix, '{guild_q}', \
         ExamineArticle, MessageArticle, X + {offset_x}, Y + {offset_y}, Z, Speed, Heading, \
         Region, Model, Size, Strength, Constitution, Dexterity, Quickness, Intelligence, Piety, \
         Empathy, Charisma, Level, Realm, EquipmentTemplateID, ItemsListTemplateID, NPCTemplateID, \
         Race, Flags, AggroLevel, AggroRange, MeleeDamageType, RespawnInterval, FactionID, \
         BodyType, HouseNumber, Brain, PathID, OwnerID, RoamingRange, IsCloakHoodUp, Gender, \
         PackageID, VisibleWeaponSlots \
         FROM Mob WHERE Mob_ID = '{reference_q}';",
        class_type_q = sql_quote(class_type),
        name_q = sql_quote(npc_name),
        guild_q = sql_quote(guild_name),
        reference_q = sql_quote(reference_mob_id),
    );
    run_remote_sql(cfg, &sql)?;
    Ok(format!(
        "Spawned '{npc_name}' ({guild_name}), offset ({offset_x}, {offset_y}) from the reference NPC."
    ))
}

#[cfg(test)]
mod tests {
    use super::*;

    fn req() -> TrainerRequest {
        TrainerRequest {
            class_id: 64,
            class_name: "Nosferatu".to_string(),
            trainer_class_ident: "NosferatuTrainer".to_string(),
            guild_name: "Nosferatu Trainer".to_string(),
            realm: "Midgard".to_string(),
            archetype_id: 38,
            archetype_name: "Rogue".to_string(),
            min_level: 5,
        }
    }

    #[test]
    fn generates_a_trainer_gated_on_the_archetype_not_the_direct_parent() {
        let code = generate_trainer_code(&req());
        assert!(code.contains("[NPCGuildScript(\"Nosferatu Trainer\", eRealm.Midgard)]"));
        assert!(code.contains("public class NosferatuTrainer : GameTrainer"));
        assert!(
            code.contains("public override eCharacterClass TrainedClass => (eCharacterClass)64;")
        );
        // Gated on the archetype's raw ID (38 = Midgard Rogue), not Shadowblade - the whole point
        // of overriding CanPromotePlayer instead of using the unreliable default resolver.
        assert!(code.contains("player.CharacterClass?.ID != 38"));
        assert!(code.contains("player.Level < 5"));
        // Braces balance (cheap sanity check the template substitution didn't mangle structure).
        assert_eq!(
            code.matches('{').count(),
            code.matches('}').count(),
            "mismatched braces:\n{code}"
        );
    }

    fn test_cfg(dir: &std::path::Path) -> SshConfig {
        SshConfig {
            host: String::new(),
            user: String::new(),
            port: 22,
            identity_file: String::new(),
            remote_server_dir: dir.to_string_lossy().to_string(),
            start_script_name: "daoc-server.sh".to_string(),
        }
    }

    fn setup_test_db(name: &str) -> std::path::PathBuf {
        let dir = std::env::temp_dir().join(format!("daoc-class-editor-trainer-test-{name}"));
        std::fs::remove_dir_all(&dir).ok();
        std::fs::create_dir_all(dir.join("data")).unwrap();
        let db = dir.join("data/opendaoc.sqlite3.db");
        let sql = "
            CREATE TABLE Mob (Mob_ID TEXT PRIMARY KEY, ClassType TEXT, TranslationId TEXT, Name TEXT,
                Suffix TEXT, Guild TEXT, ExamineArticle TEXT, MessageArticle TEXT, X INT, Y INT, Z INT,
                Speed INT, Heading INT, Region INT, Model INT, Size INT, Strength INT, Constitution INT,
                Dexterity INT, Quickness INT, Intelligence INT, Piety INT, Empathy INT, Charisma INT,
                Level INT, Realm INT, EquipmentTemplateID TEXT, ItemsListTemplateID TEXT,
                NPCTemplateID INT, Race INT, Flags INT, AggroLevel INT, AggroRange INT,
                MeleeDamageType INT, RespawnInterval INT, FactionID INT, BodyType INT, HouseNumber INT,
                Brain TEXT, PathID TEXT, OwnerID TEXT, RoamingRange INT, IsCloakHoodUp INT, Gender INT,
                PackageID TEXT, VisibleWeaponSlots INT);

            INSERT INTO Mob (Mob_ID, ClassType, Name, Guild, X, Y, Z, Speed, Heading, Region, Model,
                Size, Level, Realm, Gender, Brain, Flags, AggroLevel, AggroRange, RespawnInterval)
            VALUES ('ref-1', 'DOL.GS.Trainer.ShadowbladeTrainer', 'Hreidar', 'Shadowblade Trainer',
                35859, 35006, 8218, 0, 1094, 101, 224, 50, 50, 2, 2, 'DOL.AI.Brain.StandardMobBrain',
                0, 0, 0, 3600);
        ";
        let status = std::process::Command::new("sqlite3")
            .arg(&db)
            .arg(sql)
            .status()
            .expect("sqlite3 must be on PATH for this test");
        assert!(status.success());
        dir
    }

    #[test]
    fn finds_trainer_npcs_by_guild_search() {
        let dir = setup_test_db("find");
        let cfg = test_cfg(&dir);

        let found = find_trainer_npcs(&cfg, "Shadowblade").unwrap();
        assert_eq!(found.len(), 1);
        assert_eq!(found[0].name, "Hreidar");
        assert_eq!(found[0].mob_id, "ref-1");
        assert_eq!(found[0].x, 35859);

        assert!(find_trainer_npcs(&cfg, "NoSuchGuild").unwrap().is_empty());

        std::fs::remove_dir_all(&dir).ok();
    }

    #[test]
    fn spawns_a_new_npc_cloning_every_field_except_identity_name_guild_script_and_position() {
        let dir = setup_test_db("spawn");
        let cfg = test_cfg(&dir);

        spawn_trainer_npc(
            &cfg,
            "ref-1",
            "Nosferatu Trainer NPC",
            "Nosferatu Trainer",
            "DOL.GS.Trainer.NosferatuTrainer",
            200,
            0,
        )
        .unwrap();

        let rows = run_remote_sql_json(
            &cfg,
            "SELECT * FROM Mob WHERE Name = 'Nosferatu Trainer NPC';",
        )
        .unwrap();
        assert_eq!(rows.len(), 1);
        let row = &rows[0];
        assert_eq!(str_field(row, "Guild"), "Nosferatu Trainer");
        assert_eq!(
            str_field(row, "ClassType"),
            "DOL.GS.Trainer.NosferatuTrainer"
        );
        // Position offset applied...
        assert_eq!(int_field(row, "X"), 35859 + 200);
        assert_eq!(int_field(row, "Y"), 35006);
        // ...but every other stat cloned faithfully from the reference NPC.
        assert_eq!(int_field(row, "Z"), 8218);
        assert_eq!(int_field(row, "Heading"), 1094);
        assert_eq!(int_field(row, "Region"), 101);
        assert_eq!(int_field(row, "Model"), 224);
        assert_eq!(int_field(row, "Level"), 50);
        assert_eq!(int_field(row, "Realm"), 2);
        assert_eq!(str_field(row, "Brain"), "DOL.AI.Brain.StandardMobBrain");
        assert_eq!(int_field(row, "RespawnInterval"), 3600);
        // A fresh Mob_ID distinct from the reference's.
        assert_ne!(str_field(row, "Mob_ID"), "ref-1");

        // The original reference NPC is untouched.
        let original =
            run_remote_sql_json(&cfg, "SELECT * FROM Mob WHERE Mob_ID = 'ref-1';").unwrap();
        assert_eq!(int_field(&original[0], "X"), 35859);

        std::fs::remove_dir_all(&dir).ok();
    }
}
